import copy
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from adapters.renpy.compiler import render_story, quote
from adapters.renpy.story_model import enumerate_routes

ROOT = Path(__file__).resolve().parents[2]


class NativeAdapterTests(unittest.TestCase):
    def setUp(self):
        self.story = json.loads((ROOT / 'examples/renpy/story.json').read_text(encoding='utf-8'))

    def test_native_route_conditions_and_effects(self):
        report = enumerate_routes(self.story)
        self.assertEqual(report['errors'], [])
        self.assertEqual(len(report['routes']), 2)
        self.assertEqual({route['ending'] for route in report['routes']}, {'trust', 'other'})

    def test_compiler_emits_standard_native_dsl_and_stable_line_ids(self):
        script, images = render_story(self.story, [], [])
        self.assertIn('label start:', script)
        self.assertIn('menu:', script)
        self.assertIn('if trust >= 1:', script)
        self.assertIn('else:', script)
        self.assertIn('$ rain_line_id = "response_line"', script)
        self.assertIn('call screen ending_card', script)
        self.assertIn('return', script)
        self.assertEqual(images, '# Generated from asset_manifest.json.\n')

    def test_inline_response_and_regular_lines_bind_native_voice_manifests(self):
        script, _ = render_story(self.story, [], [], [dict(voice_id='voice_response', line_id='response_line', file='audio/response.ogg')])
        self.assertIn('voice "audio/response.ogg"', script)
        self.assertLess(script.index('voice "audio/response.ogg"'), script.index('$ rain_line_id = "response_line"'))

    def test_authored_text_cannot_create_substitutions_or_tags(self):
        text = 'literal [variable] {b}tag{/b} "quote"\nnext'
        escaped = json.loads(quote(text))
        self.assertIn('[[variable]', escaped)
        self.assertIn('{{b}', escaped)
        self.assertIn('"quote"', escaped)

    def test_invalid_routes_ids_conditions_and_effects_do_not_compile(self):
        for mutate in [
            lambda story: story['nodes'][0]['choices'][0].update(next='missing'),
            lambda story: story['nodes'][0].update(id='start'),
            lambda story: story['nodes'][3]['routes'][0].update(when={'trust': {'unknown_op': 1}}),
            lambda story: story['nodes'][0]['choices'][0].update(effects={'unrecognized': 1})
        ]:
            story = copy.deepcopy(self.story)
            mutate(story)
            with self.assertRaises(ValueError):
                render_story(story, [], [])

    def test_portable_cli_has_no_dependency_on_original_game_directories(self):
        with tempfile.TemporaryDirectory() as directory:
            result = subprocess.run([sys.executable, '-m', 'adapters.renpy', '--story', str(ROOT / 'examples/renpy/story.json'), '--out', directory], cwd=ROOT, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            generated = Path(directory, 'story_generated.rpy').read_text(encoding='utf-8')
            self.assertTrue(generated.startswith('# Generated by python -m adapters.renpy'))
            self.assertTrue(Path(directory, 'images_generated.rpy').is_file())


if __name__ == '__main__':
    unittest.main()
