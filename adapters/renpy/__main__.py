"""Portable adapter CLI; never reads or writes a released game's save data."""
import argparse
import json
from pathlib import Path
from .compiler import render_story


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--story', required=True, type=Path)
    parser.add_argument('--assets', type=Path)
    parser.add_argument('--voices', type=Path)
    parser.add_argument('--full-voices', type=Path)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    read = lambda path: json.loads(path.read_text(encoding='utf-8'))
    story = read(args.story)
    assets = read(args.assets)['assets'] if args.assets else []
    voices = read(args.voices)['voices'] if args.voices else []
    full = read(args.full_voices)['clips'] if args.full_voices else []
    script, images = render_story(story, assets, voices, full)
    script = script.replace('# Generated by python -m tools.compile_story; edit game/data/story.json.',
                            f'# Generated by python -m adapters.renpy; edit {args.story.name}.', 1)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / 'story_generated.rpy').write_text(script, encoding='utf-8')
    (args.out / 'images_generated.rpy').write_text(images, encoding='utf-8')
    print(f'Native Ren\'Py DSL generated: {args.out}')


if __name__ == '__main__':
    main()
